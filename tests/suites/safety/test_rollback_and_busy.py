import os, sys; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
from harness import *
import sqlite3, time
print("== an error rolls everything back")
fresh(); c = sqlite3.connect(APP)
c.execute("create trigger boom before update on tbl_iconinfo_2000 begin select raise(abort, 'boom'); end"); c.commit(); c.close(); before = dump()
rc, err = run()
check("an error while writing the second user: exit code 1, even the first user's rows are unchanged", rc == 1 and dump() == before, (rc, err[-200:]))
check("the notification says it was rolled back", "rolled back" in err and "откат" in err, err[-200:])
print("== an unexpected database is refused")
fresh(); c = sqlite3.connect(APP); c.execute("drop table tbl_iconinfo_2000"); c.execute("drop table tbl_iconinfo_1000")
c.execute("create table tbl_iconinfo_1000 (titleId TEXT, titleName TEXT)"); c.commit(); c.close(); before = dump(); rc, err = run()
check("a table without the column visible: exit code 1, nothing changed", rc == 1 and dump() == before, err[-150:])
fresh(); c = sqlite3.connect(APP); c.execute("drop table tbl_iconinfo_1000"); c.execute("drop table tbl_iconinfo_2000"); c.commit(); c.close(); before = dump(); rc, err = run()
check("no user tables at all: exit code 1, nothing changed", rc == 1 and dump() == before, err[-150:])
print("== the system keeps the database busy")
fresh(); before = dump(); lock = sqlite3.connect(APP, isolation_level=None); lock.execute("begin exclusive")
t0 = time.time(); rc, err = run(); lock.execute("rollback"); lock.close()
check("the program waits, then gives up: exit code 1, nothing changed", rc == 1 and dump() == before, (rc, round(time.time() - t0, 1)))
check("it did not wait forever (under 30 s)", time.time() - t0 < 30)
fresh(); lock = sqlite3.connect(APP, isolation_level=None, check_same_thread=False); lock.execute("begin immediate"); lock.execute("update tbl_version set value=value+1"); 
t0 = time.time(); import threading; threading.Timer(2.0, lambda: lock.execute("commit")).start()
rc, _ = run()
check("a short lock of the system is waited out: the tiles are hidden (exit code 0)", rc == 0 and vis(STORE) == 0, (rc, round(time.time() - t0, 1)))
print("== the system database is left as it was")
fresh(); run()
check("no journal or other files are left next to the database", [f for f in os.listdir("/tmp") if f.startswith("sth_app.db") and f != "sth_app.db"] == [])
check("the database is intact", q("pragma quick_check") == [("ok",)])
sys.exit(summary())
