import os, sys; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
from harness import *
import sqlite3
fresh(); orig = dump()
print("== the first run hides the tiles: nothing else changes")
rc, err = run()
check("both tiles of both users are hidden (visible=0), exit code 0", rc == 0 and all(vis(t, u) == 0 for t in TILES for u in USERS), (rc, err[-200:]))
set_vis(1)
check("the rest of the database is untouched (library, Plus, the game, other tables, the second user)", dump() == orig)
fresh(); rc, err = run()
check("the notification says what was done and why, in English and Russian", "tiles hidden / плитки скрыты" in err and "The tiles were shown, so they are hidden." in err and "Плитки были видны, поэтому скрываю их." in err, err[-400:])
check("the notification names both tiles", STORE in err and ALL_APPS in err, err[-300:])
log = open(LOG).read() if os.path.exists(LOG) else ""
check("last-run.log is written with the version and the same lines", log.startswith("Store Tile Hider ") and STORE in log and "read back: matches" in log and "so they are hidden" in log, log[:120])
print("== the second run shows them again")
rc, err = run()
check("the tiles are shown again (visible=1), the database equals the original", rc == 0 and dump() == orig, (rc, err[-200:]))
check("the notification says the tiles were shown, in English and Russian", "tiles shown / плитки показаны" in err and "The tiles were hidden, so they are shown again." in err and "Плитки были скрыты, поэтому возвращаю их." in err, err[-400:])
ok = True
for n in range(5):
    rc, _ = run(); ok &= rc == 0 and all(vis(t, u) == (0 if n % 2 == 0 else 1) for t in TILES for u in USERS)
check("five more runs alternate: hidden, shown, hidden, shown, hidden", ok)
print("== the state before the run decides")
fresh(); set_vis(0); rc, err = run()
check("both tiles hidden before (as after an earlier hide): the run shows them", rc == 0 and all(vis(t, u) == 1 for t in TILES for u in USERS), err[-150:])
fresh(); set_vis(0, tiles=(STORE,)); rc, err = run()
check("only one tile hidden: the run hides both (the aim of the tool is hiding)", rc == 0 and all(vis(t, u) == 0 for t in TILES for u in USERS) and "so all are hidden" in err, err[-300:])
fresh(); set_vis(0, users=("1000",)); rc, err = run()
check("the second user still sees the tiles: the run hides them for everyone", rc == 0 and all(vis(t, u) == 0 for t in TILES for u in USERS))
fresh(); c = sqlite3.connect(APP)
for u in USERS: c.execute(f"update tbl_iconinfo_{u} set visible=NULL where titleId in (?, ?)", TILES)
c.commit(); c.close(); rc, _ = run()
check("an empty (NULL) visible counts as shown: the run hides", rc == 0 and all(vis(t, u) == 0 for t in TILES for u in USERS))
print("== partial databases")
fresh(); c = sqlite3.connect(APP)
for u in USERS: c.execute(f"delete from tbl_iconinfo_{u} where titleId=?", (ALL_APPS,))
c.commit(); c.close(); rc, err = run(); first = vis(STORE); rc2, _ = run()
check("one tile missing in the database: the other one is toggled (hidden, then shown), the missing one is reported", rc == 0 and first == 0 and rc2 == 0 and vis(STORE) == 1 and "not in the database" in err, (first, vis(STORE)))
fresh(); c = sqlite3.connect(APP)
for u in USERS: c.execute(f"delete from tbl_iconinfo_{u} where titleId in (?, ?)", TILES)
c.commit(); c.close(); before = dump(); rc, err = run()
check("both tiles missing: exit code 1 and the database is unchanged", rc == 1 and dump() == before and "tiles not found" in err, (rc, err[-150:]))
fresh(); c = sqlite3.connect(APP); c.execute("drop table tbl_iconinfo_2000"); c.execute("drop table tbl_info_2000"); c.commit(); c.close()
rc, _ = run(); rc2, _ = run()
check("a console with one user works the same (hide, then show)", rc == 0 and rc2 == 0 and vis(STORE) == 1 and vis(ALL_APPS) == 1)
print("== other tiles are never touched")
fresh(); set_vis(0, tiles=(PLUS, LIBRARY)); run(); run()
check("Plus and the library, hidden by hand, stay hidden; the game stays shown", all(vis(t, u) == 0 for t in (PLUS, LIBRARY) for u in USERS) and vis(GAME) == 1)
sys.exit(summary())
